-- ============================================================
-- Створення таблиці серій
-- ============================================================

CREATE TABLE IF NOT EXISTS series (
                                      id TEXT PRIMARY KEY,
                                      name TEXT NOT NULL,
                                      description TEXT
);

-- Індекс для швидкого пошуку за назвою
CREATE INDEX IF NOT EXISTS idx_series_name ON series(name);

-- Якщо є дані в books.series, можна перенести їх в окрему таблицю
-- Але це потрібно робити обережно, оскільки серії можуть повторюватися.
-- Для простоти залишаємо таблицю порожньою.